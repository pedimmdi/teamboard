export function useWorkspaceLocale() {
  const preferences = useLocale();
  const { locale, formatNumber } = preferences;

  function ui(message: string, ...values: (string | number | null | undefined)[]) {
    const text = locale === "fa" && Object.hasOwn(persian, message) ? persian[message] : message;
    return values.length
      ? text.replace(/\{(\d+)\}/g, (_, position: string) => {
          const value = values[Number(position)];
          return typeof value === "number" ? formatNumber(value) : value ?? "";
        })
      : text;
  }

  return { ...preferences, ui };
}
