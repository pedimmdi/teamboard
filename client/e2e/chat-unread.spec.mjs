import {expect, test} from "@playwright/test";

test("chat badges total project and direct messages and older reply targets open on desktop and mobile", async ({page}) => {
  test.setTimeout(90_000);
  await page.goto("/login");
  await page.getByLabel("Email address").fill("browser-test@example.com");
  await page.getByLabel("Password", {exact: true}).fill(process.env.E2E_PASSWORD);
  await page.getByRole("button", {name: "Sign in", exact: true}).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.goto("/dashboard/workspaces/chatunread/chats");
  const workspaceNav = page.getByRole("navigation", {name: "Workspace", exact: true});
  const list = page.getByRole("complementary", {name: "Conversations"});
  await expect(workspaceNav.getByRole("link", {name: /Chats/}).getByLabel("7 unread messages", {exact: true})).toBeVisible();
  const project = list.getByRole("button", {name: /Unread project/});
  const direct = list.getByRole("button", {name: /browser-chat-teammate@example.com/});
  await expect(project.getByLabel("5 unread messages")).toBeVisible();
  await expect(direct.getByLabel("2 unread messages")).toBeVisible();
  await page.screenshot({path: "test-results/chat-unread-desktop.png", fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  const mobileNav = page.getByRole("navigation", {name: "Dashboard", exact: true});
  await expect(mobileNav.getByRole("link", {name: /Chats/}).getByLabel("7 unread messages", {exact: true})).toBeVisible();
  await page.screenshot({path: "test-results/chat-unread-mobile.png", fullPage: true});
  await page.setViewportSize({width: 1440, height: 900});
  await project.click();
  await expect(project.getByLabel("5 unread messages")).toHaveCount(0);
  await expect(workspaceNav.getByRole("link", {name: /Chats/}).getByLabel("2 unread messages", {exact: true})).toBeVisible();
  await direct.click();
  await expect(workspaceNav.getByRole("link", {name: /Chats/}).locator("[aria-label$='unread messages']")).toHaveCount(0);
  await list.getByRole("button", {name: "Long history", exact: true}).click();
  const thread = page.getByRole("region", {name: "Long history", exact: true});
  await expect(thread.getByText("Original message outside first page", {exact: true})).toHaveCount(0);
  await thread.getByRole("button", {name: "Reply to earlier message", exact: true}).click();
  await expect(thread.getByText("Original message outside first page", {exact: true})).toBeInViewport();
  await expect(thread.getByText("Load earlier messages to view the original message.")).toHaveCount(0);
  await page.screenshot({path: "test-results/chat-reply-desktop.png", fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  const footer = page.getByRole("navigation", {name: "Dashboard", exact: true});
  await expect(footer.getByRole("link")).toHaveCount(4);
  await expect(footer.getByRole("link", {name: "People", exact: true})).toHaveCount(0);
  await page.getByRole("button", {name: /Conversations/}).click();
  await list.getByRole("button", {name: "Long history", exact: true}).click();
  await thread.getByRole("button", {name: "Reply to earlier message", exact: true}).click();
  await expect(thread.getByText("Original message outside first page", {exact: true})).toBeInViewport();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({path: "test-results/chat-reply-mobile.png", fullPage: true});
});
