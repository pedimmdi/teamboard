import {expect,test} from "@playwright/test";

test("private reminders support timezone-aware CRUD, due date changes, mobile and Inbox links", async ({page})=>{
  test.setTimeout(120_000);
  await page.goto("/login");
  await page.getByLabel("Email address").fill("browser-reminder@example.com");
  await page.getByLabel("Password",{exact:true}).fill(process.env.E2E_PASSWORD);
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.goto("/dashboard/workspaces/reminders/projects");
  await page.getByRole("link",{name:/Reminder project/}).filter({visible:true}).first().click();
  await page.getByRole("button",{name:"Reminder browser task",exact:true}).click();
  const drawer=page.getByRole("dialog",{name:"Task",exact:true});
  const reminders=drawer.getByRole("region",{name:"Reminders",exact:true});
  await expect(reminders.getByText(/sent/)).toBeVisible();
  await reminders.getByRole("button",{name:"New reminder",exact:true}).click();
  await reminders.getByLabel("Timezone (IANA)").fill("Asia/Tehran");
  await reminders.getByLabel("Reminder date and time",{exact:true}).fill("2030-05-20T09:00");
  let fail=true;
  await page.route("**/tasks/*/reminders/",async route=>{
    if(route.request().method()==="POST" && fail){fail=false;await route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({detail:"Temporary reminder failure"})});}
    else await route.continue();
  });
  await reminders.getByRole("button",{name:"Create reminder",exact:true}).click();
  await expect(reminders.getByRole("alert")).toBeVisible();
  await expect(reminders.getByLabel("Reminder date and time",{exact:true})).toHaveValue("2030-05-20T09:00");
  const created=page.waitForResponse(response=>response.url().endsWith("/reminders/")&&response.request().method()==="POST"&&response.status()===201);
  await reminders.getByRole("button",{name:"Create reminder",exact:true}).click();
  const body=await(await created).json();
  expect(body.run_at).toBe("2030-05-20T05:30:00Z");
  await expect(reminders.getByText("Reminder created.",{exact:true})).toBeVisible();
  await reminders.getByRole("button",{name:"Edit reminder",exact:true}).click();
  await expect(reminders.getByLabel("Reminder date and time",{exact:true})).toHaveValue("2030-05-20T09:00");
  await reminders.getByLabel("Reminder date and time",{exact:true}).fill("2030-05-21T09:30");
  await reminders.getByRole("button",{name:"Save reminder",exact:true}).click();
  await expect(reminders.getByText("Reminder updated.",{exact:true})).toBeVisible();
  await reminders.getByRole("button",{name:"Cancel reminder",exact:true}).click();
  await expect(reminders.getByText("Reminder cancelled.",{exact:true})).toBeVisible();
  await reminders.getByRole("button",{name:"New reminder",exact:true}).click();
  await reminders.getByLabel("Reminder type").selectOption("relative");
  await reminders.getByLabel("Timezone (IANA)").fill("Asia/Tehran");
  await reminders.getByLabel("Due date preset").selectOption("1");
  await reminders.getByRole("button",{name:"Create reminder",exact:true}).click();
  await expect(reminders.getByText(/1 day\(s\) before due date/)).toBeVisible();
  await drawer.getByRole("button",{name:"Details",exact:true}).click();
  const due=new Date();due.setUTCDate(due.getUTCDate()+20);
  await drawer.getByLabel("Due date",{exact:true}).fill(due.toISOString().slice(0,10));
  await drawer.getByRole("button",{name:"Save changes",exact:true}).click();
  await expect(drawer.getByRole("button",{name:"Save changes",exact:true})).toBeDisabled();
  await expect(reminders.getByRole("button",{name:"Edit reminder",exact:true})).toBeVisible();
  await reminders.getByRole("button",{name:"Edit reminder",exact:true}).click();
  await expect(reminders.getByLabel("Local reminder time")).toHaveValue("09:00");
  await page.screenshot({path:"test-results/reminders-desktop.png",fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await reminders.getByLabel("Local reminder time").fill("10:15");
  await reminders.getByRole("button",{name:"Save reminder",exact:true}).click();
  await expect(reminders.getByText(/before due date at 10:15/)).toBeVisible();
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:"test-results/reminders-mobile.png",fullPage:true});
  await drawer.getByRole("button",{name:"Back to tasks",exact:true}).click();
  await page.goto("/dashboard/notifications");
  await page.getByRole("link",{name:"Task reminder",exact:true}).click();
  await expect(page.getByRole("dialog",{name:"Task",exact:true})).toBeVisible();
});
