import {test,expect} from "@playwright/test";
test("workspace dashboard supports scope, session restoration, views and mobile navigation",async({page})=>{
 test.setTimeout(90000);
  await page.goto("/login");
  await page.getByLabel("Email address").fill("browser-reminder@example.com");
  await page.getByLabel("Password",{exact:true}).fill(process.env.E2E_PASSWORD);
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page).toHaveURL(/\/workspaces\/[^/]+\/dashboard$/,{timeout:15000});
  const dashboard=page.getByRole("region",{name:"Workspace dashboard",exact:true});
  await expect(dashboard.getByRole("article")).toHaveCount(2);
  await expect(dashboard.getByText("Browse projects",{exact:false})).toHaveCount(0);
  await expect(dashboard.getByText("Due in 7 days",{exact:true})).toBeVisible();
  await expect(page.getByRole("navigation",{name:"Workspace",exact:true}).getByRole("link").first()).toHaveText("Dashboard");
  await page.goto("/dashboard/workspaces/dashempty");
  await expect(page).toHaveURL(/dashempty\/dashboard$/);
  await page.goto("/dashboard/workspaces");
  await page.getByRole("link",{name:/Dashboard empty workspace/}).click();
  await expect(page).toHaveURL(/dashempty\/dashboard$/);
  await page.getByRole("button",{name:"Switch workspace",exact:true}).filter({visible:true}).click();
  await page.getByRole("dialog",{name:"Switch workspace",exact:true}).getByRole("link",{name:/Dashboard empty workspace/}).click();
  await expect(page).toHaveURL(/dashempty\/dashboard$/);
  await expect(dashboard.getByRole("article",{name:"My Tasks",exact:true})).toContainText("0");
  await expect(dashboard.getByText("Reminder browser task",{exact:true})).toHaveCount(0);
  await page.goto("/login");
  await expect(page).toHaveURL(/\/workspaces\/[^/]+\/dashboard$/,{timeout:15000});
  await page.getByRole("link", { name: "Public website" }).filter({ visible: true }).click();
  await expect(page).toHaveURL("/");
  const publicHeader = page.getByRole("banner");
  await expect(publicHeader.getByRole("link", { name: "Open dashboard" })).toBeVisible();
  await publicHeader.getByRole("link", { name: "About" }).click();
  await expect(page).toHaveURL("/about");
  await publicHeader.getByRole("link", { name: "Open dashboard" }).click();
  await expect(page).toHaveURL(/\/workspaces\/[^/]+\/dashboard$/,{timeout:15000});
  await expect(dashboard.getByRole("article")).toHaveCount(2);
  const workspaceReads=[];
  const recordWorkspace=request=>{if(/\/api\/v1\/workspaces\/[^/]+\/$/.test(new URL(request.url()).pathname))workspaceReads.push(request.url());};
  page.on("request",recordWorkspace);
  await page.goto("/dashboard/workspaces/dashempty/dashboard");
  await expect(dashboard.getByRole("article")).toHaveCount(2);
  page.off("request",recordWorkspace);
  expect(workspaceReads).toHaveLength(1);
  console.log("workspace_metadata_requests",workspaceReads.length);
  await page.setViewportSize({width:390,height:844});
  const nav=page.getByRole("navigation",{name:"Dashboard",exact:true});
  await expect(nav.getByRole("link")).toHaveText(["Projects","Calendar","Dashboard",/Chats/,"Account"]);
  await expect(nav.getByRole("link").nth(2)).toHaveAttribute("aria-current","page");
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:"test-results/dashboard-mobile.png",fullPage:true});
  await page.setViewportSize({width:1440,height:900});
  await page.getByRole("button", { name: "Dark mode", exact: true }).filter({ visible: true }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await expect(dashboard.getByRole("article")).toHaveCount(2);
  await page.screenshot({path:"test-results/dashboard-dark.png",fullPage:true});
  await page.getByRole("navigation",{name:"Workspace",exact:true}).getByRole("link",{name:"Profile",exact:true}).click();
  await expect(page).toHaveURL(/\/dashboard\/profile$/);
  await expect(page.getByRole("heading",{name:"Profile",exact:true})).toBeVisible();
});
